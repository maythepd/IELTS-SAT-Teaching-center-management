import { Router } from 'express';
import { handle, role } from '../middleware.ts';
import { query } from '../database/db_connection.ts';
import { integer } from '../utils/errors.ts';
import * as courses from '../services/courses.ts';
import * as learning from '../services/learning.ts';
import * as schedules from '../services/schedules.ts';
import * as payroll from '../services/payroll.ts';
import * as tests from '../services/tests.ts';
import { permission } from '../services/accounts.ts';
import { dashboard } from '../services/dashboard.ts';
export const teacherRouter = Router();
teacherRouter.use(role('TEACHER', 'MANAGER'));
teacherRouter.use(async (req, res, next) => {
  if (req.method !== 'GET') {
    const p = req.path;
    const code = p.includes('target') ? 'TARGET_WRITE' : p.includes('courses') ? 'COURSE_WRITE' : p.includes('grade') ? 'GRADING_WRITE' : p.includes('tests') ? 'TEST_WRITE' : p.includes('events') ? 'SCHEDULE_WRITE' : p.includes('report') ? 'REPORT_WRITE' : p.includes('record') ? 'SESSION_WRITE' : 'LEARNING_WRITE';
    await permission(req.user, code);
  }
  next();
});
teacherRouter.get('/dashboard', handle(req => dashboard(req.user, String(req.query.period || ''))));
teacherRouter.get('/classes', handle(req => courses.listClasses(req.user)));
teacherRouter.get('/classes/:id', handle(req => courses.classDetail(req.user, integer(req.params.id))));
teacherRouter.get('/courses', handle(req => courses.listCourses(req.user, req.query.keyword)));
teacherRouter.get('/courses/:id', handle(req => courses.courseDetail(integer(req.params.id))));
teacherRouter.get('/classes/:id/materials', handle(req => learning.materials(req.user, integer(req.params.id))));
teacherRouter.post('/classes/:id/materials', handle(req => learning.saveMaterial(req.user, integer(req.params.id), req.body)));
teacherRouter.patch('/classes/:classId/materials/:id', handle(req => learning.saveMaterial(req.user, integer(req.params.classId), req.body, integer(req.params.id))));
teacherRouter.get('/classes/:id/assignments', handle(req => learning.assignments(req.user, integer(req.params.id))));
teacherRouter.post('/classes/:id/assignments', handle(req => learning.saveAssignment(req.user, integer(req.params.id), req.body)));
teacherRouter.patch('/classes/:classId/assignments/:id', handle(req => learning.saveAssignment(req.user, integer(req.params.classId), req.body, integer(req.params.id))));
teacherRouter.get('/assignments/:id/submissions', handle(req => learning.submissions(req.user, integer(req.params.id))));
teacherRouter.get('/submissions/:id', handle(req => learning.submission(req.user, integer(req.params.id))));
teacherRouter.put('/submissions/:id/grade', handle(req => learning.grade(req.user, integer(req.params.id), req.body)));
teacherRouter.get('/students/:id/progress', handle(req => learning.progress(req.user, integer(req.params.id), req.query)));
teacherRouter.get('/students/:id/assessments/:score', handle(req => learning.assessmentDetail(req.user, integer(req.params.id), integer(req.params.score))));
teacherRouter.put('/students/:id/target', handle(req => learning.setTarget(req.user, integer(req.params.id), req.body)));
teacherRouter.get('/events', handle(req => schedules.events(req.user, req.query)));
teacherRouter.post('/events', handle(req => schedules.saveEvent(req.user, req.body)));
teacherRouter.patch('/events/:id', handle(req => schedules.saveEvent(req.user, req.body, integer(req.params.id))));
teacherRouter.get('/sessions/:id', handle(req => schedules.session(req.user, integer(req.params.id))));
teacherRouter.put('/sessions/:id/record', handle(req => schedules.recordSession(req.user, integer(req.params.id), req.body)));
teacherRouter.get('/sessions/:id/reports/:student', handle(req => schedules.report(req.user, integer(req.params.id), integer(req.params.student))));
teacherRouter.put('/sessions/:id/reports/:student', handle(req => schedules.report(req.user, integer(req.params.id), integer(req.params.student), req.body)));
teacherRouter.get('/income', handle(req => payroll.payroll(req.user, String(req.query.period || ''))));
teacherRouter.get('/tests', handle(req => tests.testList(req.user, req.query.class_id ? integer(req.query.class_id) : null)));
teacherRouter.get('/tests/:id', handle(req => tests.testDetail(req.user, integer(req.params.id))));
teacherRouter.post('/classes/:id/tests', handle(req => tests.saveTest(req.user, integer(req.params.id), req.body)));
teacherRouter.patch('/classes/:classId/tests/:id', handle(req => tests.saveTest(req.user, integer(req.params.classId), req.body, integer(req.params.id))));
teacherRouter.get('/tests/:id/attempts', handle(req => tests.attempts(req.user, integer(req.params.id))));
teacherRouter.get('/attempts/:id', handle(req => tests.attempt(req.user, integer(req.params.id))));
teacherRouter.put('/attempts/:id/grade', handle(req => tests.gradeTest(req.user, integer(req.params.id), req.body)));
